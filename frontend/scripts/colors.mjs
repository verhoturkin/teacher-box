// Writes the colours that depend on constants only (stage 376, ADR-0034): the M3 roles of the default
// appearance, the roles of the label colours and the stamp of the colour engine. The app takes them
// from `core/theme/generated-colors.ts` instead of computing them with
// `@material/material-color-utilities` at every start. Run `npm run colors` after changing the engine
// (`color-engine.ts`, `color.ts`), its inputs (`computed-colors.ts`, the Aura palettes) or the version
// of the library; `generated-colors.spec.ts` fails while the constants differ from the computed ones.
import { writeFileSync } from 'node:fs';
import { register } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as prettier from 'prettier';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const THEME = join(ROOT, 'src', 'app', 'core', 'theme');
const TARGET = join(THEME, 'generated-colors.ts');

// the engine is TypeScript and the library 0.4.0 imports its files without `.js`: see the loader
register('./colors-loader.mjs', import.meta.url);
const { computedColors } = await import(pathToFileURL(join(THEME, 'computed-colors.ts')).href);
const { DEFAULT_ROLES, LABEL_ROLES, ENGINE_STAMP } = computedColors();

const constant = (value) => JSON.stringify(value, null, 2);
const source = `// Generated by scripts/colors.mjs (\`npm run colors\`) — do not edit. The colours that depend on constants
// only (stage 376): computed by the colour engine once, here, not at every start of the app.
import type { SchemeRoles } from './color-scheme';
import type { LabelColor, LabelRoles } from './label-colors';

/** The roles of the default colour (indigo) with the default appearance (Fidelity, standard contrast). */
export const DEFAULT_ROLES: SchemeRoles = ${constant(DEFAULT_ROLES)};

/** The roles of the label colours in both themes. */
export const LABEL_ROLES: Readonly<
  Record<LabelColor, { readonly light: LabelRoles; readonly dark: LabelRoles }>
> = ${constant(LABEL_ROLES)};

/** The stamp of the colour engine: roles kept on a device under another stamp are computed again. */
export const ENGINE_STAMP = ${constant(ENGINE_STAMP)};
`;
writeFileSync(
  TARGET,
  await prettier.format(source, { ...(await prettier.resolveConfig(TARGET)), filepath: TARGET }),
);
console.log(`Colours written to ${TARGET}; the engine stamp is ${ENGINE_STAMP}.`);
