// Builds the icons of the app (ADR-0046): finds every `tb-i-<name>` class in src/, takes those
// Material Symbols Rounded glyphs out of the full variable font (5 MB) into a small subset and writes
// the code points next to it; PrimeNG's own SVG icons get our symbols as CSS masks (prime-icons.scss).
// Run `npm run icons` after adding or removing an icon; the design-rules test fails while a used icon
// is missing from the map or a mapped one is no longer used.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as fontkit from 'fontkit';
import * as prettier from 'prettier';
import subsetFont from 'subset-font';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const THEME = join(SRC, 'app', 'core', 'theme');
const MAP = join(THEME, 'icons.scss');
const FONT = join(THEME, 'symbols.woff2');
const PRIME_MAP = join(THEME, 'prime-icons.scss');
const FULL_FONT = join(ROOT, 'node_modules', 'material-symbols', 'material-symbols-rounded.woff2');

/**
 * PrimeNG's icons (`<svg data-p-icon="…">`) that the app shows → our symbols (design-system §1 «Icons»).
 * The rest of PrimeNG's icons never show in the app.
 */
const PRIME = {
  'angle-double-left': 'first_page',
  'angle-double-right': 'last_page',
  'angle-down': 'keyboard_arrow_down',
  'angle-left': 'chevron_left',
  'angle-right': 'chevron_right',
  'angle-up': 'keyboard_arrow_up',
  calendar: 'calendar_month',
  check: 'check',
  'chevron-down': 'arrow_drop_down',
  'chevron-left': 'chevron_left',
  'chevron-right': 'chevron_right',
  'chevron-up': 'arrow_drop_up',
  'exclamation-triangle': 'warning',
  'info-circle': 'info',
  minus: 'remove',
  search: 'search',
  'sort-alt': 'unfold_more',
  'sort-amount-down': 'arrow_downward',
  'sort-amount-up-alt': 'arrow_upward',
  spinner: 'progress_activity',
  times: 'close',
  'times-circle': 'error',
};

/** Only the axes the app moves: fill (active section), grade (dark theme), optical size 20–24. */
const AXES = { wght: 400, opsz: { min: 20, max: 24 }, GRAD: { min: -25, max: 0 } };

function sources(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      return sources(path);
    }
    return /\.(ts|html|scss)$/.test(entry.name) && !entry.name.endsWith('.spec.ts') && path !== MAP
      ? [readFileSync(path, 'utf8')]
      : [];
  });
}

const names = [
  ...new Set(sources(SRC).flatMap((text) => Array.from(text.matchAll(/(?:\btb-i-|<tb-assist-chip\s+icon=")([a-z0-9_]+)/g), (m) => m[1]))),
].sort();

const full = readFileSync(FULL_FONT);
const font = fontkit.create(full);
const codeOf = new Map();
for (const code of font.characterSet) {
  if (code >= 0xe000) {
    codeOf.set(font.glyphForCodePoint(code).id, code);
  }
}

function glyphOf(name) {
  const glyphs = font.layout(name).glyphs;
  if (glyphs.length !== 1 || !codeOf.has(glyphs[0].id)) {
    throw new Error(`No Material Symbol «${name}» (https://fonts.google.com/icons)`);
  }
  return glyphs[0];
}

const codes = names.map((name) => codeOf.get(glyphOf(name).id));

const subset = await subsetFont(full, String.fromCodePoint(...codes), {
  targetFormat: 'woff2',
  variationAxes: AXES,
});
writeFileSync(FONT, subset);

const entries = names.map((name, i) => `  '${name}': '${codes[i].toString(16)}',`).join('\n');
const map = `// Generated by \`npm run icons\` (scripts/icons.mjs) from the \`tb-i-<name>\` classes in src/ — don't edit.
// Material Symbols Rounded (ADR-0046): the name → its code point in the subset font symbols.woff2.
$icons: (
${entries}
);
`;
writeFileSync(MAP, await prettier.format(map, { ...(await prettier.resolveConfig(MAP)), filepath: MAP }));

// The outline at the font's default axes (outlined, weight 400, optical size 24, grade 0); the font's
// y axis points up, a 960-unit em like Google's own SVG downloads.
const masks = Object.entries(PRIME).map(([icon, symbol]) => {
  const path = glyphOf(symbol).path.toSVG().replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 960 960'><path transform='matrix(1 0 0 -1 0 960)' d='${path}'/></svg>`;
  return `  '${icon}': '${svg.replace(/</g, '%3C').replace(/>/g, '%3E').replace(/'/g, '%27')}',`;
});
const primeMap = `// Generated by \`npm run icons\` (scripts/icons.mjs) — don't edit.
// PrimeNG's icons drawn with Material Symbols Rounded (ADR-0046): the icon → the symbol's outline as an SVG mask.
$prime-icons: (
${masks.join('\n')}
);
`;
writeFileSync(
  PRIME_MAP,
  await prettier.format(primeMap, { ...(await prettier.resolveConfig(PRIME_MAP)), filepath: PRIME_MAP }),
);

console.log(`${String(names.length)} icons, symbols.woff2 ${String(Math.round(subset.length / 1024))} KB`);
